using PracticeTL.Api.Models;

namespace PracticeTL.Api.Data;

public static class BenefitSeeder
{
    public static void Seed(AppDbContext db)
    {
        if (db.Benefits.Any())
            return;

        var items = new (string Title, string Text)[]
        {
            ("Онбординг в компанию", "Наставник поможет быстро включиться в работу."),
            ("Поездки и обучение", "Курсы, конференции, мастер-классы за счет компании. Корпоративная библиотека и тренинги для тех, кто любит учиться."),
            ("Рост и грейды", "Вместе отмечаем победы и откровенно обсуждаем точки роста один на один. Пересматриваем зарплату и задачи в соответствии с твоими достижениями и реалиями рынка."),
            ("Здоровье и спорт", "С первого месяца работы — абонементы на спорт, после испытательного срока — ДМС со стоматологией и сеансы в «Ясно». Проводим совместные тренировки и ходим в тренажерный зал в офисе."),
            ("Обед", "Кормим в офисе за счет компании, а удаленным сотрудникам компенсируем затраты на обеды. На кухне офиса всегда можно найти что-нибудь вкусное."),
            ("Бонусы", "Премии и мерч, финансовая поддержка от компании на важные события в жизни. Ежегодный бонус на покупку техники и компенсация командировок в офис для удаленных сотрудников."),
            ("Околорабочая жизнь", "Отдыхать мы любим так же, как и работать :) Ежегодно у нас проходят музыкальные фестивали, квизы, спортивные турниры, кэмпинги, сплавы и другие внутренние мероприятия. Два раза в год традиционно выезжаем всей компанией на выходные: летом — кэмпинг на Волге, зимой — горнолыжка."),
            ("Обустройство удаленного рабочего места", "Предоставляем мощный ноутбук, компенсируем затраты на интернет и расходные материалы.")
        };

        var order = 1;
        foreach (var it in items)
        {
            db.Benefits.Add(new Benefit
            {
                Title = it.Title,
                Text = it.Text,
                SortOrder = order++
            });
        }

        db.SaveChanges();
    }
}
